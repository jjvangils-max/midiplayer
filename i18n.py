_current = "en"


def set_language(lang):
    global _current
    if lang in _STRINGS:
        _current = lang


def get_language():
    return _current


def t(key, **fmt):
    s = _STRINGS.get(_current, _STRINGS["en"]).get(key, key)
    if fmt:
        try:
            return s.format(**fmt)
        except (KeyError, IndexError):
            return s
    return s
